#!/bin/bash
# 分月填补2023-2024数据,避免数据库锁竞争

echo "开始分月填补2023-2024数据缺口..."
echo "使用10个worker,每月约20个交易日×1000股=20000任务"
echo "预计每月耗时: ~5小时"
echo ""

# 2023年各月
months=(
    "2023-01-01 2023-01-31"
    "2023-02-01 2023-02-28"
    "2023-03-01 2023-03-31"
    "2023-04-01 2023-04-30"
    "2023-05-01 2023-05-31"
    "2023-06-01 2023-06-30"
    "2023-07-01 2023-07-31"
    "2023-08-01 2023-08-31"
    "2023-09-01 2023-09-30"
    "2023-10-01 2023-10-31"
    "2023-11-01 2023-11-30"
    "2023-12-01 2023-12-31"
    "2024-01-01 2024-01-31"
    "2024-02-01 2024-02-29"
    "2024-03-01 2024-03-31"
    "2024-04-01 2024-04-30"
    "2024-05-01 2024-05-31"
    "2024-06-01 2024-06-30"
    "2024-07-01 2024-07-31"
    "2024-08-01 2024-08-31"
    "2024-09-01 2024-09-30"
    "2024-10-01 2024-10-31"
    "2024-11-01 2024-11-30"
    "2024-12-01 2024-12-31"
)

for month in "${months[@]}"; do
    read start end <<< "$month"
    echo "========================================="
    echo "处理: $start 至 $end"
    echo "========================================="

    python3 fill_gap_lockfree.py \
        --start "$start" \
        --end "$end" \
        --stocks 1000 \
        --workers 10

    if [ $? -eq 0 ]; then
        echo "✅ $start 至 $end 完成"
    else
        echo "❌ $start 至 $end 失败"
        exit 1
    fi

    echo ""
    sleep 5  # 短暂休息,释放资源
done

echo "========================================="
echo "全部完成！"
echo "========================================="

# 统计最终结果
python3 -c "
import sqlite3
conn = sqlite3.connect('data_adapter/stock_data.db')
cursor = conn.execute('''
    SELECT COUNT(*) FROM v39_feature_cache
    WHERE trade_date >= '2023-01-01' AND trade_date <= '2024-12-31'
''')
total = cursor.fetchone()[0]
print(f'2023-2024期间共缓存: {total:,} 个样本')
conn.close()
"

const TAXONOMY_COLOR_MAPS = { sw_l1: SW_L1_COLORS, sw_l2: SW_L2_COLORS, concept: CONCEPT_COLORS };

function sectorColor(taxonomy, name) {
  const m = TAXONOMY_COLOR_MAPS[taxonomy] || {};
  const key = name.replace(/[ⅡⅢ]$/, '');
  if (m[key]) return m[key];
  // 兜底: 名称 hash → 固定色相 (跨日期恒定)
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
  return `hsl(${h % 360}, 42%, 46%)`;
}

function sectorTextColor(bg) {
  if (!bg.startsWith('#')) return '#fff';   // hsl 兜底色亮度固定, 白字
  const r = parseInt(bg.slice(1, 3), 16), g = parseInt(bg.slice(3, 5), 16), b = parseInt(bg.slice(5, 7), 16);
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255 > 0.55 ? '#111' : '#fff';
}

function fmtDateShort(d) { return d.slice(5).replace('-', '/'); }  // 2026-07-10 → 07/10

/**
 * 轮动日历表格: 列=日期(升序), 行=当日排名
 * @param dates      ['2026-06-01', ...] 升序
 * @param cellsByDate {date: [item, ...]} 已排序
 * @param renderCell item => {label: 主文本, sub: 右侧小字(可空), title: 悬浮提示, name: 板块名}
 */
function buildCalendarTable(taxonomy, dates, cellsByDate, renderCell, colW = 140) {
  const maxRows = Math.max(1, ...dates.map(d => (cellsByDate[d] || []).length));
  let h = `<table class="rotation-calendar" style="min-width:${dates.length * colW}px"><thead><tr>`;
  dates.forEach(d => { h += `<th style="width:${colW}px">${fmtDateShort(d)}</th>`; });
  h += '</tr></thead><tbody>';
  for (let ri = 0; ri < maxRows; ri++) {
    h += '<tr>';
    dates.forEach(d => {
      const items = cellsByDate[d] || [];
      if (ri < items.length) {
        const c = renderCell(items[ri]);
        const bg = sectorColor(taxonomy, c.name);
        h += `<td><span class="sector-chip" style="background:${bg};color:${sectorTextColor(bg)}" ` +
             `title="${c.title}">${c.label}${c.sub ? `<small>${c.sub}</small>` : ''}</span></td>`;
      } else {
        h += '<td></td>';
      }
    });
    h += '</tr>';
  }
  return h + '</tbody></table>';
}

